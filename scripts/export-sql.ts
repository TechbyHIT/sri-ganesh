import fs from "fs";
import path from "path";
import { allServices } from "../src/data/all-services";
import { cities } from "../src/data/cities";
import { districtByName, geo, geoDistricts, getDistrict, hubCityOf, ulbsForMandal } from "../src/data/geo";
import { galleryPhotos } from "../src/data/gallery-manifest";
import { services as builtIn } from "../src/data/services";
import { allLocalities, readStore } from "../src/lib/store";
