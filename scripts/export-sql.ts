const withLinks = process.argv.includes("--links");
const outDir = path.join(process.cwd(), "db");

function q(value: unknown): string {
  if (value === null || value === undefined || value === "") return "NULL";
  if (typeof value === "boolean") return value ? "TRUE" : "FALSE";
  if (typeof value === "number") return String(value);
  if (Array.isArray(value)) return `ARRAY[${value.map(q).join(", ")}]::TEXT[]`;
  return `'${String(value).replace(/'/g, "''")}'`;
}

function insert(table: string, columns: string[], rows: unknown[][], batch = 500) {
  const out: string[] = [];
  for (let start = 0; start < rows.length; start += batch) {
    const values = rows.slice(start, start + batch).map((row) => `  (${row.map(q).join(", ")})`).join(",\n");
    out.push(`INSERT INTO ${table} (${columns.join(", ")}) VALUES\n${values};`);
  }
  return out.join("\n");
}

const sql: string[] = ["-- Generated by scripts/export-sql.ts. Do not edit by hand.", "BEGIN;", "TRUNCATE states, location_sources, districts, revenue_divisions, mandals, cities, towns, villages, localities, services, service_locations, images, seo_pages, seo_content, faqs, internal_links RESTART IDENTITY CASCADE;"];

sql.push(insert("states", ["id", "slug", "name", "code"], [[1, geo.state.slug, geo.state.name, "AP"]]));

const sourceIds = new Map<string, number>();
const sourceRows: unknown[][] = [];
for (const district of geoDistricts) {
  for (const source of district.sources) {
    if (sourceIds.has(source.url)) continue;
    sourceIds.set(source.url, sourceIds.size + 1);
    sourceRows.push([sourceIds.size, source.url, source.title, new URL(source.url).hostname, source.accessed || null, source.covers]);
  }
}

const districtIds = new Map<string, number>();
const divisionIds = new Map<string, number>();
const mandalIds = new Map<string, number>();
const districtRows: unknown[][] = [];
const divisionRows: unknown[][] = [];
const mandalRows: unknown[][] = [];
const townRows: unknown[][] = [];
const ulbMandal = new Map<string, number>();
geoDistricts.forEach((district, index) => {
  const id = index + 1;
  districtIds.set(district.slug, id);
  districtRows.push([id, 1, district.slug, district.name, district.headquarters, district.region, district.officialSite, hubCityOf(district)?.slug, district.verified, district.verifiedAt || null, district.notes]);
  for (const division of district.divisions) {
    divisionIds.set(`${district.slug}/${division.slug}`, divisionIds.size + 1);
    divisionRows.push([divisionIds.size, id, division.slug, division.name]);
  }
  for (const mandal of district.mandals) {
    mandalIds.set(`${district.slug}/${mandal.slug}`, mandalIds.size + 1);
    mandalRows.push([mandalIds.size, id, mandal.division ? divisionIds.get(`${district.slug}/${mandal.division}`) : null, mandal.slug, mandal.name]);
    for (const ulb of ulbsForMandal(district, mandal)) ulbMandal.set(`${district.slug}/${ulb.slug}`, mandalIds.size);
  }
});

const citySlugs = new Set(cities.map((city) => city.slug));
const cityIds = new Map<string, number>();
const cityRows = cities.map((city, index) => {
  cityIds.set(city.slug, index + 1);
  const district = districtByName(city.district);
  const ulb = district?.ulbs.find((item) => item.slug === city.slug);
  return [index + 1, district ? districtIds.get(district.slug) : null, district && ulb ? ulbMandal.get(`${district.slug}/${ulb.slug}`) ?? null : null, city.slug, city.name, ulb?.type ?? null, city.region, true, city.intro, city.housing, city.climate, city.visitNote];
});
for (const district of geoDistricts) {
  for (const ulb of district.ulbs) {
    if (citySlugs.has(ulb.slug)) continue;
    townRows.push([townRows.length + 1, districtIds.get(district.slug), ulbMandal.get(`${district.slug}/${ulb.slug}`) ?? null, ulb.slug, ulb.name, ulb.type]);
  }
}

const villageRows: unknown[][] = [];
const localityRows: unknown[][] = [];
const localityIds = new Map<string, number>();
for (const city of cities) {
  for (const area of city.areas) {
    localityIds.set(`${city.slug}/${area.slug}`, localityRows.length + 1);
    localityRows.push([localityRows.length + 1, cityIds.get(city.slug), null, area.slug, area.name, "area", area.detail, true]);
  }
}
const seenVillages = new Set<string>();
const seenLocalities = new Set<string>();
for (const row of allLocalities()) {
  const mandalId = mandalIds.get(`${row.district}/${row.mandal}`);
  if (!mandalId) continue;
  if (row.kind === "village") {
    const key = `${mandalId}/${row.slug}`;
    if (seenVillages.has(key)) continue;
    seenVillages.add(key);
    if (row.source && !sourceIds.has(row.source)) {
      sourceIds.set(row.source, sourceIds.size + 1);
      sourceRows.push([sourceIds.size, row.source, `Village list: ${row.district}/${row.mandal}`, new URL(row.source).hostname, row.createdAt.slice(0, 10), ["villages"]]);
    }
    villageRows.push([villageRows.length + 1, mandalId, row.slug, row.name, row.source ? sourceIds.get(row.source) : null, row.verified, row.createdAt]);
  } else {
    const key = `${mandalId}/${row.slug}/${row.kind}`;
    if (seenLocalities.has(key)) continue;
    seenLocalities.add(key);
    localityRows.push([localityRows.length + 1, null, mandalId, row.slug, row.name, row.kind, null, row.verified]);
  }
}

const serviceList = allServices();
const serviceIds = new Map(serviceList.map((service, index) => [service.slug, index + 1]));
const builtInSlugs = new Set(builtIn.map((service) => service.slug));
const serviceRows = serviceList.map((service) => [serviceIds.get(service.slug), service.slug, service.name, service.group, service.summary, service.lede, builtInSlugs.has(service.slug), true]);

const catalog = getCatalog();
const records = readRegistry()?.records ?? [];
const recordByPath = new Map(records.map((record) => [record.path, record]));
const overrides = allOverrides();

const placeBySlug = new Map(Object.values(readStore("places")).filter((place) => place.enabled).map((place) => [place.slug, place]));
const serviceLocationRows: unknown[][] = [];
for (const page of catalog.pages) {
  if (page.kind !== "service-city" && page.kind !== "service-area") continue;
  const { service, city, area } = page.params;
  const placeMandal = placeBySlug.get(city ?? "");
  serviceLocationRows.push([
    serviceLocationRows.length + 1,
    service ? serviceIds.get(service) : null,
    city ? cityIds.get(city) ?? null : null,
    city && area ? localityIds.get(`${city}/${area}`) ?? null : null,
    placeMandal ? mandalIds.get(`${placeMandal.district}/${placeMandal.mandal}`) ?? null : null,
    page.status === "publish",
  ]);
}

const imageRows: unknown[][] = [
  ...galleryPhotos.map((photo) => [photo.id, photo.src, photo.alt, serviceIds.get(photo.services[0] ?? photo.category) ?? null, null, false, geo.generatedAt]),
  ...readStore("uploads").map((upload) => [upload.id, `/media/${upload.file}`, upload.alt, serviceIds.get(upload.service) ?? null, districtIds.get(upload.place) ?? null, true, upload.createdAt]),
];

const pageIds = new Map<string, number>();
const pageRows: unknown[][] = [];
for (const page of catalog.pages) {
  const record = recordByPath.get(page.path);
  const district = page.params.district ? getDistrict(page.params.district) ?? districtByName(page.params.district) : undefined;
  pageIds.set(page.path, pageRows.length + 1);
  pageRows.push([
    pageRows.length + 1,
    page.path,
    page.kind,
    record?.status ?? page.status,
    record ? record.index : page.index,
    overrides[page.path] ?? null,
    record?.score ?? page.score,
    page.title,
    record?.reasons ?? page.reasons,
    record?.version ?? 0,
    page.inputHash,
    page.params.service ? serviceIds.get(page.params.service) ?? null : null,
    page.params.city ? cityIds.get(page.params.city) ?? null : null,
    district ? districtIds.get(district.slug) : null,
    district && page.params.mandal ? mandalIds.get(`${district.slug}/${page.params.mandal}`) ?? null : null,
    record?.updatedAt ?? geo.generatedAt,
  ]);
}

const contentRows: unknown[][] = [];
for (const [pagePath, edit] of Object.entries(readStore("pageEdits"))) {
  const pageId = pageIds.get(pagePath);
  if (pageId) contentRows.push([contentRows.length + 1, pageId, null, edit.title, edit.description, edit.h1, edit.intro, null, null, null, true, edit.updatedAt]);
}
for (const place of Object.values(readStore("places"))) {
  const mandalId = mandalIds.get(`${place.district}/${place.mandal}`);
  if (mandalId) contentRows.push([contentRows.length + 1, null, mandalId, place.name, null, null, place.intro, place.housing, place.visitNote, null, place.enabled, place.updatedAt]);
}

const faqRows: unknown[][] = [];
for (const service of serviceList) {
  service.faqs.forEach((faq, index) => faqRows.push([faqRows.length + 1, serviceIds.get(service.slug), null, faq.q, faq.a, index]));
}
for (const [pagePath, edit] of Object.entries(readStore("pageEdits"))) {
  const pageId = pageIds.get(pagePath);
  edit.faqs?.forEach((faq, index) => pageId && faqRows.push([faqRows.length + 1, null, pageId, faq.q, faq.a, index]));
}

sql.push(
  insert("location_sources", ["id", "url", "title", "publisher", "accessed_on", "covers"], sourceRows),
  insert("districts", ["id", "state_id", "slug", "name", "headquarters", "region", "official_site", "hub_city_slug", "verified", "last_verified_on", "notes"], districtRows),
  insert("revenue_divisions", ["id", "district_id", "slug", "name"], divisionRows),
  insert("mandals", ["id", "district_id", "division_id", "slug", "name"], mandalRows),
  insert("cities", ["id", "district_id", "mandal_id", "slug", "name", "ulb_type", "region", "has_page", "intro", "housing", "climate", "visit_note"], cityRows),
  insert("towns", ["id", "district_id", "mandal_id", "slug", "name", "ulb_type"], townRows),
  insert("villages", ["id", "mandal_id", "slug", "name", "source_id", "verified", "created_at"], villageRows),
  insert("localities", ["id", "city_id", "mandal_id", "slug", "name", "kind", "detail", "verified"], localityRows),
  insert("services", ["id", "slug", "name", "service_group", "summary", "lede", "built_in", "active"], serviceRows),
  insert("service_locations", ["id", "service_id", "city_id", "locality_id", "mandal_id", "available"], serviceLocationRows),
  insert("images", ["id", "src", "alt", "service_id", "district_id", "uploaded", "created_at"], imageRows),
  insert("seo_pages", ["id", "path", "kind", "status", "indexable", "manual_status", "score", "title", "reasons", "template_version", "input_hash", "service_id", "city_id", "district_id", "mandal_id", "updated_at"], pageRows),
  insert("seo_content", ["id", "page_id", "mandal_id", "title", "description", "h1", "intro", "housing", "visit_note", "image_id", "enabled", "updated_at"], contentRows),
  insert("faqs", ["id", "service_id", "page_id", "question", "answer", "sort_order"], faqRows),
);
for (const table of ["location_sources", "districts", "revenue_divisions", "mandals", "cities", "towns", "villages", "localities", "services", "service_locations", "seo_pages", "seo_content", "faqs"]) {
  sql.push(`SELECT setval(pg_get_serial_sequence('${table}', 'id'), GREATEST((SELECT MAX(id) FROM ${table}), 1));`);
}
sql.push("COMMIT;", "");

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, "seed.sql"), sql.filter(Boolean).join("\n\n"));

let linkCount = 0;
if (withLinks) {
  const linkRows: unknown[][] = [];
  for (const page of catalog.pages) {
    const from = pageIds.get(page.path);
    if (!from || page.status === "exclude") continue;
    for (const module of page.modules) {
      if (module.type !== "links") continue;
      for (const link of module.links) if (link.href) linkRows.push([from, link.href, link.label, slugify(module.title)]);
    }
  }
  linkCount = linkRows.length;
  fs.writeFileSync(path.join(outDir, "seed-links.sql"), ["BEGIN;", "TRUNCATE internal_links RESTART IDENTITY;", insert("internal_links", ["from_page_id", "to_path", "anchor", "module"], linkRows, 1000), "COMMIT;", ""].join("\n\n"));
}

